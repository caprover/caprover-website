def transform(contents: str, rules: list[tuple[str,str]]) -> str:
    # Avoid changing shell/Dockerfile/JSON/YAML code blocks.
    outside: list[str] = []
    code = []
    protected = False
    for line in contents.splitlines(keepends=True):
        if re.match(r'^\s*(`{3,}|~{3,})', line):
            protected = not protected
            outside.append(line)
            continue
        if protected:
            outside.append(line)
            continue
        for old,new in rules:
            if old in line:
                line=line.replace(old,new)
        outside.append(line)
    return "".join(outside)

